package com.example.forensics

import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.RectF
import com.example.data.model.PaymentProvider

enum class SampleScenario(
    val title: String,
    val description: String,
    val provider: PaymentProvider,
    val expectedTid: String,
    val expectedAmount: Double,
    val isFake: Boolean,
    val injectSms: Boolean,
    val injectSmsAmount: Double
) {
    GENUINE_EASYPAISA(
        title = "Genuine EasyPaisa (Rs. 2,500)",
        description = "Legitimate slip with matching 3737 merchant SMS in inbox.",
        provider = PaymentProvider.EASYPAISA,
        expectedTid = "EP8391028471",
        expectedAmount = 2500.0,
        isFake = false,
        injectSms = true,
        injectSmsAmount = 2500.0
    ),
    FAKE_EASYPAISA_NO_SMS(
        title = "Fake EasyPaisa Slip (Rs. 45,000)",
        description = "Counterfeit screenshot generated by fake app. No 3737 SMS received!",
        provider = PaymentProvider.EASYPAISA,
        expectedTid = "EP9988776655",
        expectedAmount = 45000.0,
        isFake = true,
        injectSms = false,
        injectSmsAmount = 0.0
    ),
    TAMPERED_JAZZCASH_AMOUNT(
        title = "Tampered JazzCash (Rs. 15,000 vs Rs. 150)",
        description = "Shopkeeper received Rs. 150, but customer edited screenshot to Rs. 15,000.",
        provider = PaymentProvider.JAZZCASH,
        expectedTid = "JC1029384756",
        expectedAmount = 15000.0,
        isFake = true,
        injectSms = true,
        injectSmsAmount = 150.0 // Mismatch!
    ),
    GENUINE_SADAPAY(
        title = "Genuine SadaPay (Rs. 6,800)",
        description = "Legitimate SadaPay transfer with matching SMS alert.",
        provider = PaymentProvider.SADAPAY,
        expectedTid = "SP7749102841",
        expectedAmount = 6800.0,
        isFake = false,
        injectSms = true,
        injectSmsAmount = 6800.0
    )
}

object SampleSlipGenerator {

    fun generateSlipBitmap(scenario: SampleScenario): Bitmap {
        val width = 600
        val height = 950
        val bitmap = Bitmap.createBitmap(width, height, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(bitmap)

        // Background
        val bgPaint = Paint().apply {
            color = Color.parseColor("#F8F9FA")
            style = Paint.Style.FILL
        }
        canvas.drawRect(0f, 0f, width.toFloat(), height.toFloat(), bgPaint)

        // Header brand bar
        val headerColor = when (scenario.provider) {
            PaymentProvider.EASYPAISA -> Color.parseColor("#00A859")
            PaymentProvider.JAZZCASH -> Color.parseColor("#E2001A")
            PaymentProvider.SADAPAY -> Color.parseColor("#FF5252")
            PaymentProvider.NAYAPAY -> Color.parseColor("#FF6D00")
            else -> Color.parseColor("#1E88E5")
        }
        val headerPaint = Paint().apply {
            color = headerColor
            style = Paint.Style.FILL
        }
        canvas.drawRect(0f, 0f, width.toFloat(), 180f, headerPaint)

        // Title text
        val titlePaint = Paint().apply {
            color = Color.WHITE
            textSize = 34f
            isFakeBoldText = true
            textAlign = Paint.Align.CENTER
        }
        canvas.drawText("${scenario.provider.displayName} Successful", (width / 2).toFloat(), 90f, titlePaint)

        val subTitlePaint = Paint().apply {
            color = Color.parseColor("#E0E0E0")
            textSize = 20f
            textAlign = Paint.Align.CENTER
        }
        canvas.drawText("Transaction Receipt", (width / 2).toFloat(), 130f, subTitlePaint)

        // Central Card
        val cardPaint = Paint().apply {
            color = Color.WHITE
            style = Paint.Style.FILL
        }
        val cardRect = RectF(40f, 220f, (width - 40).toFloat(), 860f)
        canvas.drawRoundRect(cardRect, 24f, 24f, cardPaint)

        // Amount Display
        val amountLabelPaint = Paint().apply {
            color = Color.parseColor("#757575")
            textSize = 20f
            textAlign = Paint.Align.CENTER
        }
        canvas.drawText("Amount Transferred", (width / 2).toFloat(), 290f, amountLabelPaint)

        val amountValPaint = Paint().apply {
            color = Color.parseColor("#212121")
            textSize = 52f
            isFakeBoldText = true
            textAlign = Paint.Align.CENTER
        }
        val formattedAmount = "Rs. %,.0f".format(scenario.expectedAmount)
        canvas.drawText(formattedAmount, (width / 2).toFloat(), 360f, amountValPaint)

        // If tampered scenario, deliberately introduce jagged compression / pixel noise around amount to simulate digital editing
        if (scenario.isFake) {
            val noisePaint = Paint().apply {
                color = Color.argb(40, 255, 0, 0)
                strokeWidth = 2f
            }
            for (i in 0 until 40) {
                val rx = (200..400).random().toFloat()
                val ry = (320..380).random().toFloat()
                canvas.drawCircle(rx, ry, (1..4).random().toFloat(), noisePaint)
            }
        }

        // Divider
        val linePaint = Paint().apply {
            color = Color.parseColor("#EEEEEE")
            strokeWidth = 2f
        }
        canvas.drawLine(70f, 410f, (width - 70).toFloat(), 410f, linePaint)

        // Key Value Pairs
        drawKeyValue(canvas, "Transaction ID (TID)", scenario.expectedTid, 470f, width)
        drawKeyValue(canvas, "Receiver Account", "0300-8492019 (Shopkeeper)", 550f, width)
        drawKeyValue(canvas, "Sender Name", "Customer Transfer", 630f, width)
        drawKeyValue(canvas, "Status", "Success / Confirmed", 710f, width, Color.parseColor("#2E7D32"))
        drawKeyValue(canvas, "Date & Time", "Today, 02:45 PM", 790f, width)

        return bitmap
    }

    private fun drawKeyValue(
        canvas: Canvas,
        key: String,
        value: String,
        y: Float,
        width: Int,
        valColor: Int = Color.parseColor("#212121")
    ) {
        val keyPaint = Paint().apply {
            color = Color.parseColor("#757575")
            textSize = 20f
        }
        canvas.drawText(key, 70f, y, keyPaint)

        val valPaint = Paint().apply {
            color = valColor
            textSize = 21f
            isFakeBoldText = true
            textAlign = Paint.Align.RIGHT
        }
        canvas.drawText(value, (width - 70).toFloat(), y, valPaint)
    }
}
